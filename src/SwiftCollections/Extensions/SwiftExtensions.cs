using System;
using System.Collections.Generic;
using System.Runtime.CompilerServices;
using Chronicler.Diagnostics;

namespace SwiftCollections;

/// <summary>
/// Provides extension methods for collection manipulation and utility functions.
/// </summary>
public static class SwiftExtensions
{
    /// <summary>
    /// Populates an array with values generated by a specified provider function.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="array">The caller-owned array; population mutates it, while TryIndex only reads it.</param>
    /// <param name="provider">The factory invoked once per visited index, in increasing order; the index overload
    /// receives that zero-based index.</param>
    /// <returns>The same input array after replacing every cell.</returns>
    /// <exception cref="T:System.NullReferenceException">array is null, or a supplied provider is null when a
    /// non-empty array is visited.</exception>
    /// <remarks>
    /// Writes occur in increasing index order. Factory/constructor exceptions leave an already populated prefix;
    /// no rollback is performed.
    /// </remarks>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static T[] Populate<T>(this T[] array, Func<T> provider)
    {
        for (int i = 0; i < array.Length; i++)
            array[i] = provider();
        return array;
    }

    /// <summary>
    /// Populates an array with values generated by a provider function that accepts the current index.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="array">The caller-owned array; population mutates it, while TryIndex only reads it.</param>
    /// <param name="provider">The factory invoked once per visited index, in increasing order; the index overload
    /// receives that zero-based index.</param>
    /// <returns>The same input array after replacing every cell.</returns>
    /// <exception cref="T:System.NullReferenceException">array is null, or a supplied provider is null when a
    /// non-empty array is visited.</exception>
    /// <remarks>
    /// Writes occur in increasing index order. Factory/constructor exceptions leave an already populated prefix;
    /// no rollback is performed.
    /// </remarks>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static T[] Populate<T>(this T[] array, Func<int, T> provider)
    {
        for (int i = 0; i < array.Length; i++)
            array[i] = provider(i);
        return array;
    }

    /// <summary>
    /// Populates an array with new instances of the specified type. The type must have a parameterless
    /// constructor.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="array">The caller-owned array; population mutates it, while TryIndex only reads it.</param>
    /// <returns>The same input array after replacing every cell.</returns>
    /// <exception cref="T:System.NullReferenceException">array is null, or a supplied provider is null when a
    /// non-empty array is visited.</exception>
    /// <remarks>
    /// Writes occur in increasing index order. Factory/constructor exceptions leave an already populated prefix;
    /// no rollback is performed.
    /// </remarks>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static T[] Populate<T>(this T[] array) where T : new()
    {
        for (int i = 0; i < array.Length; i++)
            array[i] = new T();
        return array;
    }

    /// <summary>
    /// Attempts to retrieve an element from the array at the specified index. Returns true if the index is valid
    /// and the element is retrieved; otherwise, returns false.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="array">The caller-owned array; population mutates it, while TryIndex only reads it.</param>
    /// <param name="index">The signed array index; negative indices count from the end (-1 is last).</param>
    /// <param name="result">Receives the element on success; default(T) on failure.</param>
    /// <returns>true if the adjusted index identifies an element; false for null arrays or out-of-range indices,
    /// with result set to default. No mutation.</returns>
    public static bool TryIndex<T>(this T[] array, int index, out T result)
    {
        if (array != null)
        {
            if (index < 0)
            {
                // Support negative indices to access elements from the end
                index = array.Length + index;
            }
            if (index >= 0 && index < array.Length)
            {
                result = array[index];
                return true;
            }
        }

        result = default!;
        return false;
    }

    /// <summary>
    /// An iterator that yields the elements of the source collection in a random order using the specified random
    /// number generator.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="source">The source sequence; its elements are read without modifying the source
    /// collection.</param>
    /// <param name="rng">The retained or supplied non-null random generator; its state advances as random
    /// selections are made.</param>
    /// <returns>A deferred shuffled sequence over a fresh shallow buffer on each enumeration.</returns>
    /// <exception cref="T:System.ArgumentNullException">source or rng is null when enumeration
    /// begins.</exception>
    /// <remarks>
    /// Validation and source copying occur when enumeration starts, not when called. The supplied generator is
    /// retained and advanced lazily. Re-enumeration re-reads the source and consumes additional random state.
    /// Determinism depends on source order and the generator implementation/state.
    /// </remarks>
    public static IEnumerable<T> Shuffle<T>(this IEnumerable<T> source, Random rng)
    {
        ChronicleGuard.ThrowIfNull(source, nameof(source));
        ChronicleGuard.ThrowIfNull(rng, nameof(rng));

        SwiftList<T> buffer = new(source);
        int n = buffer.Count;
        while (n > 0)
        {
            int k = rng.Next(n);
            n--;
            // Swap the selected element with the last unshuffled element
            (buffer[k], buffer[n]) = (buffer[n], buffer[k]);
            yield return buffer[n];
        }
    }

    /// <summary>
    /// Shuffles the elements of the list in place using the specified random number generator.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="list">The caller-owned list; must be non-null and writable for shuffling.</param>
    /// <param name="rng">The retained or supplied non-null random generator; its state advances as random
    /// selections are made.</param>
    /// <exception cref="T:System.ArgumentNullException">list or rng is null.</exception>
    /// <remarks>
    /// Fisher-Yates swaps mutate the list in place and consume generator state. A read-only list, throwing
    /// indexer or generator can leave partial shuffling; reproducibility depends on list order and generator
    /// behavior.
    /// </remarks>
    public static void ShuffleInPlace<T>(this IList<T> list, Random rng)
    {
        ChronicleGuard.ThrowIfNull(list, nameof(list));
        ChronicleGuard.ThrowIfNull(rng, nameof(rng));

        int n = list.Count;
        while (n > 1)
        {
            n--;
            int k = rng.Next(n + 1);
            (list[n], list[k]) = (list[k], list[n]);
        }
    }

    /// <summary>
    /// Determines whether a sequence contains any elements.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="source">The source sequence; its elements are read without modifying the source
    /// collection.</param>
    /// <returns>true if one MoveNext succeeds; false if the sequence is empty.</returns>
    /// <exception cref="T:System.ArgumentNullException">source is null.</exception>
    /// <remarks>
    /// Creates and disposes an enumerator after one advance; enumeration side effects can occur. Does not buffer
    /// the sequence.
    /// </remarks>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static bool IsPopulated<T>(this IEnumerable<T> source)
    {
        ChronicleGuard.ThrowIfNull(source, nameof(source));
        using IEnumerator<T> enumerator = source.GetEnumerator();
        return enumerator.MoveNext();
    }

    /// <summary>
    /// Determines whether the collection is not null and contains any elements.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="source">The source sequence; its elements are read without modifying the source
    /// collection.</param>
    /// <returns>true if one MoveNext succeeds; false if the sequence is empty or null.</returns>
    /// <remarks>
    /// Creates and disposes an enumerator after one advance; enumeration side effects can occur. Does not buffer
    /// the sequence.
    /// </remarks>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static bool IsPopulatedSafe<T>(this IEnumerable<T> source) => source != null && source.IsPopulated();

    /// <summary>
    /// Gets the element at the specified index from the end (1-based). For example, FromEnd(1) returns the last
    /// item, FromEnd(2) returns second-to-last.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="source">The source sequence; its elements are read without modifying the source
    /// collection.</param>
    /// <param name="reverseIndex">The one-based distance from the end: 1 is last; valid through the element
    /// count.</param>
    /// <returns>The element at the requested one-based distance from the end.</returns>
    /// <exception cref="T:System.ArgumentOutOfRangeException">The requested distance is zero, negative, or
    /// exceeds the source count.</exception>
    /// <exception cref="T:System.ArgumentNullException">The source/list is null.</exception>
    /// <remarks>
    /// Reads without removal, including PopLast. The SwiftList overload reads directly; other enumerables are
    /// fully buffered into a new SwiftList before indexing.
    /// </remarks>
    public static T FromEnd<T>(this IEnumerable<T> source, int reverseIndex)
    {
        if (source is SwiftList<T> swift)
            return swift.FromEnd(reverseIndex);

        // fallback for generic IEnumerable
        var buffer = new SwiftList<T>(source);
        return buffer.FromEnd(reverseIndex);
    }

    /// <summary>
    /// Gets the element at the specified index from the end (1-based) from SwiftList.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="list">The caller-owned list; must be non-null and writable for shuffling.</param>
    /// <param name="reverseIndex">The one-based distance from the end: 1 is last; valid through the element
    /// count.</param>
    /// <returns>The element at the requested one-based distance from the end.</returns>
    /// <exception cref="T:System.ArgumentOutOfRangeException">The requested distance is zero, negative, or
    /// exceeds the source count.</exception>
    /// <exception cref="T:System.NullReferenceException">The source/list is null.</exception>
    /// <remarks>
    /// Reads without removal, including PopLast. The SwiftList overload reads directly; other enumerables are
    /// fully buffered into a new SwiftList before indexing.
    /// </remarks>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static T FromEnd<T>(this SwiftList<T> list, int reverseIndex)
    {
        ChronicleGuard.ThrowIfArgumentOutOfRange(reverseIndex <= 0 || reverseIndex > list.Count, reverseIndex, nameof(reverseIndex));
        return list[^reverseIndex];
    }

    /// <summary>
    /// Returns the last item in the sequence.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="source">The source sequence; its elements are read without modifying the source
    /// collection.</param>
    /// <returns>The element last in the sequence.</returns>
    /// <exception cref="T:System.ArgumentOutOfRangeException">The requested distance is zero, negative, or
    /// exceeds the source count.</exception>
    /// <exception cref="T:System.ArgumentNullException">The source/list is null.</exception>
    /// <remarks>
    /// Reads without removal, including PopLast. The SwiftList overload reads directly; other enumerables are
    /// fully buffered into a new SwiftList before indexing.
    /// </remarks>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public static T PopLast<T>(this IEnumerable<T> source) => source.FromEnd(1);

    /// <summary>
    /// Bypasses a specified number of elements from the end and then returns the remaining elements.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="source">The source sequence; its elements are read without modifying the source
    /// collection.</param>
    /// <param name="count">The non-negative number of trailing elements to omit; zero yields the whole
    /// sequence.</param>
    /// <returns>A deferred sequence containing all but the last count elements, in original order.</returns>
    /// <exception cref="T:System.ArgumentNullException">source is null when enumeration begins.</exception>
    /// <exception cref="T:System.ArgumentOutOfRangeException">count is negative when enumeration
    /// begins.</exception>
    /// <remarks>
    /// Validation occurs when enumeration begins. Buffers up to count trailing elements (and a transient next
    /// item). Counts at least as large as the sequence length yield no elements. Re-enumeration consumes the
    /// source again.
    /// </remarks>
    public static IEnumerable<T> SkipFromEnd<T>(this IEnumerable<T> source, int count)
    {
        ChronicleGuard.ThrowIfNull(source, nameof(source));
        ChronicleGuard.ThrowIfNegative(count, nameof(count));

        SwiftQueue<T> buffer = new();

        foreach (T item in source)
        {
            buffer.Enqueue(item);
            if (buffer.Count > count)
                yield return buffer.Dequeue();
        }
    }

    /// <summary>
    /// Returns the second-to-last item in the sequence.
    /// </summary>
    /// <typeparam name="T">The element type.</typeparam>
    /// <param name="source">The source sequence; its elements are read without modifying the source
    /// collection.</param>
    /// <returns>The element second from the end.</returns>
    /// <exception cref="T:System.ArgumentOutOfRangeException">The requested distance is zero, negative, or
    /// exceeds the source count.</exception>
    /// <exception cref="T:System.ArgumentNullException">The source/list is null.</exception>
    /// <remarks>
    /// Reads without removal, including PopLast. The SwiftList overload reads directly; other enumerables are
    /// fully buffered into a new SwiftList before indexing.
    /// </remarks>
    public static T SecondToLast<T>(this IEnumerable<T> source) => source.FromEnd(2);
}
